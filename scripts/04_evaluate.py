"""Step 4 of the offline pipeline: evaluate the recommender against the baseline.

1. Retrieval Recall@k: for up to --sample restaurants, take one older review
   that was NOT used to build the restaurant vectors, use it as the query, and
   check whether its own restaurant ranks in the top k.
2. Twenty test queries: hybrid top 5 next to the popularity baseline top 5,
   with empty columns for two teammates to mark each result relevant or not.

Writes docs/evaluation.md.

Usage (from the repository root):
    python scripts/04_evaluate.py --city Philadelphia
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from recommender import config  # noqa: E402
from recommender.preprocessing import clean_reviews  # noqa: E402
from recommender.ranking import Engine, Filters  # noqa: E402

TEST_QUERIES = [
    "quiet date-night spot with great pasta",
    "fast, cheap lunch",
    "brunch with great coffee and no long wait",
    "vegan-friendly tacos",
    "lively place for a group birthday",
    "authentic ramen on a cold night",
    "best cheesesteak, no frills",
    "romantic dinner with a good wine list",
    "family-friendly pizza with friendly staff",
    "late-night food after a concert",
    "gluten-free options that actually taste good",
    "sushi worth the price",
    "cozy coffee shop to work from",
    "spicy food, big portions, low prices",
    "outdoor seating for a summer evening",
    "fresh seafood with a view",
    "quick breakfast before work",
    "fancy anniversary dinner",
    "good vegetarian Indian food",
    "dessert place with amazing pastries",
]


def recall_at_k(engine: Engine, reviews: pd.DataFrame, used: int, sample: int, ks=(1, 5, 10)):
    """Recall@k using held-out reviews (older than the `used` most recent ones)."""
    ordered = reviews.sort_values("date", ascending=False)
    rank_in_restaurant = ordered.groupby("business_id").cumcount()
    held_out = ordered[rank_in_restaurant == used]  # the first review not in the index
    held_out = held_out[held_out["business_id"].isin(engine.restaurants.index)]
    held_out = held_out.sample(min(sample, len(held_out)), random_state=42)
    if held_out.empty:
        return None

    query_vecs = engine.encoder(held_out["text"].tolist())
    sims = query_vecs @ engine.matrix.T
    target_rows = engine.restaurants.loc[held_out["business_id"], "row"].to_numpy()
    target_sims = sims[np.arange(len(held_out)), target_rows]
    ranks = (sims > target_sims[:, None]).sum(axis=1)  # 0 = ranked first
    n = len(engine.restaurants)
    return {
        "queries": len(held_out),
        "restaurants": n,
        **{f"recall@{k}": float((ranks < k).mean()) for k in ks},
        **{f"random@{k}": k / n for k in ks},
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate the recommender.")
    parser.add_argument("--artifacts", default=str(config.ARTIFACTS_DIR))
    parser.add_argument("--city", default=None, help="restrict the 20 test queries to one city")
    parser.add_argument("--sample", type=int, default=1000)
    parser.add_argument("--out", default="docs/evaluation.md")
    args = parser.parse_args()

    engine = Engine.load(args.artifacts)
    reviews = clean_reviews(pd.read_parquet(Path(args.artifacts) / config.REVIEWS_FILE))
    recall = recall_at_k(engine, reviews, used=config.REVIEWS_PER_RESTAURANT, sample=args.sample)

    lines = [
        "# Evaluation",
        "",
        f"Generated by `scripts/04_evaluate.py` on {date.today().isoformat()}.",
        "",
        "## Retrieval recall",
        "",
    ]
    if recall:
        lines += [
            f"{recall['queries']} held-out reviews (not used to build the index) used as queries "
            f"against {recall['restaurants']} restaurants. Recall@k = share of queries whose own "
            "restaurant ranks in the top k; random = what chance would give.",
            "",
            "| Metric | Model | Random |",
            "| --- | --- | --- |",
        ]
        for k in (1, 5, 10):
            lines.append(f"| Recall@{k} | {recall[f'recall@{k}']:.1%} | {recall[f'random@{k}']:.2%} |")
    else:
        lines.append("Not enough reviews per restaurant to hold one out.")

    filters = Filters(city=args.city) if args.city else None
    lines += [
        "",
        "## Test queries: hybrid vs popularity baseline",
        "",
        "Two teammates mark each top-5 result relevant (y) or not (n). "
        "The hybrid passes if it has more relevant results than the baseline overall.",
        "",
    ]
    baseline = [r["name"] for r in engine.baseline(filters, k=5)]
    for query in TEST_QUERIES:
        hybrid = [r["name"] for r in engine.rank(query, filters, k=5)]
        lines += [f"### {query}", "", "| # | Hybrid | Relevant? | Baseline | Relevant? |",
                  "| --- | --- | --- | --- | --- |"]
        for i in range(5):
            h = hybrid[i] if i < len(hybrid) else ""
            b = baseline[i] if i < len(baseline) else ""
            lines.append(f"| {i + 1} | {h} |  | {b} |  |")
        lines.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out}")
    if recall:
        print({k: round(v, 3) for k, v in recall.items() if k.startswith("recall")})


if __name__ == "__main__":
    main()
